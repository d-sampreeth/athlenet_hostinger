CREATE TABLE IF NOT EXISTS users (
 id BIGSERIAL PRIMARY KEY, username VARCHAR(150) UNIQUE NOT NULL,
 email VARCHAR(254) UNIQUE NOT NULL, password_hash TEXT NOT NULL,
 first_name VARCHAR(150) DEFAULT '', last_name VARCHAR(150) DEFAULT '',
 date_of_birth DATE, marital_status VARCHAR(30),
 is_active BOOLEAN DEFAULT TRUE, created_at TIMESTAMPTZ DEFAULT NOW()
);
ALTER TABLE users ADD COLUMN IF NOT EXISTS date_of_birth DATE;
ALTER TABLE users ADD COLUMN IF NOT EXISTS marital_status VARCHAR(30);
CREATE TABLE IF NOT EXISTS profiles (
 id BIGSERIAL PRIMARY KEY, user_id BIGINT UNIQUE NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 role VARCHAR(20) NOT NULL DEFAULT 'user' CHECK(role IN ('user','player','coach')),
 phone VARCHAR(20) DEFAULT '', phone_key VARCHAR(10) UNIQUE,
 location VARCHAR(120) DEFAULT '', pincode VARCHAR(6) DEFAULT '',
 bio TEXT DEFAULT '', interests TEXT DEFAULT '', photo TEXT DEFAULT '',
 created_at TIMESTAMPTZ DEFAULT NOW()
);
ALTER TABLE profiles ALTER COLUMN interests TYPE TEXT;
CREATE TABLE IF NOT EXISTS coach_profiles (
 id BIGSERIAL PRIMARY KEY, profile_id BIGINT UNIQUE NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
 age INT, gender VARCHAR(30) DEFAULT '', sport VARCHAR(50) DEFAULT '', experience INT DEFAULT 0,
 academy VARCHAR(150) DEFAULT '', certificate TEXT DEFAULT '', government_recognition VARCHAR(150) DEFAULT '',
 verified BOOLEAN DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS player_profiles (
 id BIGSERIAL PRIMARY KEY, profile_id BIGINT UNIQUE NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
 age INT, gender VARCHAR(30) DEFAULT '', sport VARCHAR(50) DEFAULT '', level VARCHAR(30) DEFAULT '', district VARCHAR(80) DEFAULT '',
 state VARCHAR(80) DEFAULT '', experience INT DEFAULT 0, ranking VARCHAR(80) DEFAULT '', statistics TEXT DEFAULT ''
);
ALTER TABLE player_profiles ADD COLUMN IF NOT EXISTS gender VARCHAR(30) DEFAULT '';
CREATE TABLE IF NOT EXISTS achievements (
 id BIGSERIAL PRIMARY KEY, player_id BIGINT NOT NULL REFERENCES player_profiles(id) ON DELETE CASCADE,
 title VARCHAR(160) NOT NULL, description TEXT DEFAULT '', year INT, proof TEXT DEFAULT '', created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS opportunities (
 id BIGSERIAL PRIMARY KEY, coach_id BIGINT NOT NULL REFERENCES coach_profiles(id) ON DELETE CASCADE,
 title VARCHAR(180) NOT NULL, description TEXT NOT NULL, sport VARCHAR(50) NOT NULL, location VARCHAR(150) NOT NULL,
 event_date DATE NOT NULL, last_date DATE NOT NULL, eligibility TEXT DEFAULT '', slots INT DEFAULT 20,
 created_at TIMESTAMPTZ DEFAULT NOW(), active BOOLEAN DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS opportunity_applications (
 id BIGSERIAL PRIMARY KEY, opportunity_id BIGINT NOT NULL REFERENCES opportunities(id) ON DELETE CASCADE,
 player_id BIGINT NOT NULL REFERENCES player_profiles(id) ON DELETE CASCADE, message TEXT DEFAULT '',
 status VARCHAR(20) DEFAULT 'pending', applied_at TIMESTAMPTZ DEFAULT NOW(), UNIQUE(opportunity_id,player_id)
);
CREATE TABLE IF NOT EXISTS posts (
 id BIGSERIAL PRIMARY KEY, author_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 content TEXT NOT NULL, image TEXT DEFAULT '', post_type VARCHAR(30) DEFAULT 'discussion',
 sport VARCHAR(50) DEFAULT '', created_at TIMESTAMPTZ DEFAULT NOW(), updated_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS comments (
 id BIGSERIAL PRIMARY KEY, post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, text TEXT NOT NULL, created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS likes (
 id BIGSERIAL PRIMARY KEY, post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, created_at TIMESTAMPTZ DEFAULT NOW(), UNIQUE(post_id,user_id)
);
CREATE TABLE IF NOT EXISTS follows (
 id BIGSERIAL PRIMARY KEY, follower_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 following_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, created_at TIMESTAMPTZ DEFAULT NOW(),
 UNIQUE(follower_id,following_id), CHECK(follower_id <> following_id)
);
CREATE TABLE IF NOT EXISTS news (
 id BIGSERIAL PRIMARY KEY, title VARCHAR(220) NOT NULL, summary TEXT NOT NULL, content TEXT DEFAULT '',
 location VARCHAR(120) DEFAULT '', pincode VARCHAR(6) DEFAULT '', sport VARCHAR(50) DEFAULT '',
 source_url TEXT DEFAULT '', image TEXT DEFAULT '', published_at TIMESTAMPTZ DEFAULT NOW(),
 featured BOOLEAN DEFAULT FALSE, active BOOLEAN DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS conversations (
 id BIGSERIAL PRIMARY KEY, user1_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 user2_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, updated_at TIMESTAMPTZ DEFAULT NOW(),
 UNIQUE(user1_id,user2_id), CHECK(user1_id <> user2_id)
);
CREATE TABLE IF NOT EXISTS messages (
 id BIGSERIAL PRIMARY KEY, conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
 sender_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, text TEXT NOT NULL,
 created_at TIMESTAMPTZ DEFAULT NOW(), read BOOLEAN DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS notifications (
 id BIGSERIAL PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 message VARCHAR(255) NOT NULL, link VARCHAR(255) DEFAULT '', read BOOLEAN DEFAULT FALSE, created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_posts_created ON posts(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_follows_following ON follows(following_id);
CREATE INDEX IF NOT EXISTS idx_opportunities_created ON opportunities(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_messages_conversation ON messages(conversation_id,created_at);
